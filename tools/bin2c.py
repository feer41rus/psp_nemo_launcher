#!/usr/bin/env python3
"""Embed a binary file as a C array: bin2c.py <input> <output.c> <symbol>."""
import sys


def main(src, dst, name):
    data = open(src, "rb").read()
    with open(dst, "w") as f:
        f.write("// Generated by tools/bin2c.py — do not edit.\n")
        f.write(f"const unsigned int {name}_size = {len(data)};\n")
        f.write(f"const unsigned char {name}[] __attribute__((aligned(16))) = {{\n")
        for i in range(0, len(data), 16):
            f.write("    " + ", ".join(str(b) for b in data[i:i + 16]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main(*sys.argv[1:4])
