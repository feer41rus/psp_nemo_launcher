#!/usr/bin/env python3
"""Bitmap font for the Control Center plugin (1.2.4): Inter Regular 13 px, 4-bit alpha, glyphs that the
window needs (ASCII, Russian, a few symbols). Writes src/core/ccfont_data.c."""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "assets/fonts/src/Inter-Regular.ttf")
OUT = os.path.join(ROOT, "src/core/ccfont_data.c")
SIZE, LINE = 13, 15
HEIGHT = 17   # CCFONT_HEIGHT in ccfont.h: every glyph, descenders included
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(0x410, 0x450)] + list("ЁёŸ·‹›—%")


def main():
    font = ImageFont.truetype(TTF, SIZE)
    ascent, _ = font.getmetrics()
    glyphs, bits = [], []
    cps = sorted(set(ord(c) for c in CHARS if c != "Ÿ"))
    for cp in cps:
        ch = chr(cp)
        adv = round(font.getlength(ch))
        img = Image.new("L", (SIZE * 2, LINE + 6), 0)
        ImageDraw.Draw(img).text((2, 0), ch, font=font, fill=255)
        box = img.getbbox()
        if not box:
            glyphs.append((cp, 0, 0, adv, 0, 0, len(bits)))
            continue
        x0, y0, x1, y1 = box
        crop = img.crop(box)
        w, h = crop.size
        start = len(bits)
        px = [v >> 4 for v in crop.getdata()]
        if len(px) % 2:
            px.append(0)
        for i in range(0, len(px), 2):
            bits.append(px[i] | (px[i + 1] << 4))
        glyphs.append((cp, w, h, adv, y0, x0 - 2, start))
    with open(OUT, "w") as f:
        f.write("// Generated by tools/make_cc_font.py from Inter Regular (SIL OFL 1.1) - do not edit.\n")
        f.write('#include "ccfont.h"\n\n')
        f.write("const CcGlyph ccfont_glyphs[] = {\n")
        for cp, w, h, adv, top, left, off in glyphs:
            f.write(f"    {{ 0x{cp:04x}, {w}, {h}, {adv}, {top}, {left}, {off} }},\n")
        f.write("};\nconst int ccfont_count = %d;\n\nconst uint8_t ccfont_bits[] = {\n" % len(glyphs))
        for i in range(0, len(bits), 16):
            f.write("    " + ", ".join(str(b) for b in bits[i:i + 16]) + ",\n")
        f.write("};\n")
    deepest = max(top + h for _, _, h, _, top, _, _ in glyphs)
    assert deepest <= HEIGHT, f"glyphs reach row {deepest}, CCFONT_HEIGHT is {HEIGHT}"
    print(f"{len(glyphs)} glyphs, {len(bits)} bytes, deepest row {deepest}")


if __name__ == "__main__":
    main()
